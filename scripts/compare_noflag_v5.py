"""Compare v5 main histories (run with the n-gram block) against no-flag reruns of the same histories.

Usage: python3 scripts/compare_noflag_v5.py FLAG_DIR NOFLAG_PATH [NOFLAG_PATH ...] [--out FILE]
FLAG_DIR is results/main_v5/raw; each NOFLAG_PATH is a JSON file or a directory of them (step 6 output,
results/main_v5/main_noflag/...). Histories are paired by (model, topic, order, condition).

Checks first that each pair is identical up to the block's first changed turn: same turn texts, and the same
categories at every clean checkpoint. That must hold because both runs are greedy and the block changes nothing
before it fires. It then compares the touched checkpoints (unlabelled prose and probe, no discount) and the
primary trajectory. Pure Python, no torch."""
import argparse
import json
from collections import Counter
from pathlib import Path

import analyze_v5 as an


def load_any(paths):
    out = {}
    for p in map(Path, paths):
        for f in (sorted(p.glob('*.json')) if p.is_dir() else [p]):
            h = json.loads(f.read_text())
            if h.get('design') == 'ladder_v5' and h.get('kind') == 'main':
                out[an.history_id(h)] = h
    return out


def compare_pair(flag, noflag):
    """One row of facts for a (flagged, no-flag) pair."""
    touch = an.ngram_touch(flag)
    first = touch['first_turn'] if touch and touch['touched'] else None
    stop = first if first is not None else len(flag['turns'])
    prefix_same = all(a['text'] == b['text'] for a, b in zip(flag['turns'][:stop], noflag['turns'][:stop])) \
        and len(noflag['turns']) >= min(stop, len(flag['turns']))
    cf, _ = an.checkpoints(flag)
    cn, _ = an.checkpoints(noflag)
    clean_same, touched = True, []
    for idx in an.CHECKPOINTS:
        for ro in ('prose', 'probe'):
            a, b = cf.get((idx, False, ro)), cn.get((idx, False, ro))
            if first is None or idx < first:
                clean_same &= a == b or b is None and noflag.get('status') != 'complete'
            else:
                touched.append((idx, ro, a, b))
    return {'first': first, 'prefix_same': prefix_same, 'clean_same': clean_same, 'touched': touched,
            'traj_flag': an.trajectory(cf), 'traj_noflag': an.trajectory(cn),
            'status': (flag.get('status'), noflag.get('status'))}


def report(flags, noflags):
    pairs = sorted(k for k in noflags if k in flags)
    md = ['# n-gram block: flagged vs no-flag reruns', '',
          'Generated by `scripts/compare_noflag_v5.py`. Checkpoint index = main turn index (0 opening, 3/5 exposure, '
          '9 release). "-" means the no-flag history stopped before that readout.', '',
          f'Pairs: {len(pairs)}. No-flag histories without a flagged partner: '
          f'{sorted(k for k in noflags if k not in flags) or "none"}.', '']
    rows, ck_rows, split = [], [], Counter()
    for k in pairs:
        c = compare_pair(flags[k], noflags[k])
        rows.append([*k, c['status'][0], c['status'][1], c['first'], 'yes' if c['prefix_same'] else '**NO**',
                     'yes' if c['clean_same'] else '**NO**', c['traj_flag']['outcome'], c['traj_noflag']['outcome']])
        for idx, ro, a, b in c['touched']:
            ck_rows.append([*k[:3], idx, ro, a or '-', b or '-',
                            '' if a == b else 'no-flag stopped' if b is None else 'changed'])
            if ro == 'prose':
                for run, cat in (('flag', a), ('noflag', b)):
                    if cat and cat != 'unresolved':
                        split[(run, 'n')] += 1; split[(run, 'split')] += cat.startswith('split')
    md += ['## Pairs', '', an.table(rows, ['model', 'topic', 'order', 'condition', 'status flag', 'status no-flag',
                                           'first touched turn', 'identical before it', 'clean checkpoints equal',
                                           'outcome flag', 'outcome no-flag']), '']
    md += ['## Touched checkpoints (no discount)', '',
           an.table(ck_rows, ['model', 'topic', 'order', 'checkpoint', 'readout', 'flag', 'no-flag', '']), '']
    rate = lambda run: f"{split[(run, 'split')]}/{split[(run, 'n')]}" if split[(run, 'n')] else '-'
    md += ['## Prose split at touched checkpoints', '', an.table([['flag', rate('flag')], ['no-flag', rate('noflag')]],
                                                                 ['run', 'split / resolved']), '']
    return '\n'.join(md) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('flag')
    ap.add_argument('noflag', nargs='+')
    ap.add_argument('--out')
    a = ap.parse_args()
    md = report(load_any([a.flag]), load_any(a.noflag))
    if a.out:
        Path(a.out).write_text(md)
    print(md)


if __name__ == '__main__':
    main()
