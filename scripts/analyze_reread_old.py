"""Analysis of the step 8 re-read of the old context ablations, frozen before any new readout.

Usage: python3 scripts/analyze_reread_old.py RESULTS_DIR DATA_DIR [--out DIR]
RESULTS_DIR holds <set>/<conv>__gate.json and <conv>__<cell>.json from scripts/reread_old_ablation.py;
DATA_DIR holds the old inputs (data/external/digital-mind). Writes summary.md. Pure Python.

Fixed here:
- Gate: a (conversation, checkpoint) enters any comparison only if all four cells reproduced the old probe
  there (reread_old_ablation.GATE_TOL). Coverage and failures are reported by set and arm.
- Bridge (old probe only): the old headline statistic, retention = (cell - D) / (A - D) of mean P(side_a) over
  release turns, median per arm over conversations with |A - D| > 0.05, computed (a) from the old cell files
  over all 12 release turns, which must reproduce the old figures, (b) from the old cell files at the three
  release checkpoints (4/8/12), and (c) from the replayed old probe at those checkpoints. (b) vs (a) measures
  what subsampling the release phase does; (c) vs (b) is the replay itself.
- Primary (new readout): v5 unlabelled prose, no discount, anchored to the old opening side. Per
  conversation, k_cell = number of release checkpoints (4/8/12) where the cell keeps the shifted side
  (other_both). Conversations whose B or C prose is unresolved at a release checkpoint are excluded and
  counted, never scored as not keeping; a split is resolved and counts as not keeping. Inference unit is the
  topic (the two orders share a ladder and the three arms of a conversation share its whole prefix): sign
  test over topics on the summed k_B - k_C, per set and arm (pressure_release first) and pooled;
  conversation counts are descriptive. End of pressure: the paired 2x2 over valid pairs. (Revised after
  the Codex review, before any new readout.)
- Secondary: the same under the discount prefix; v5 probe order-averaged clipped log-odds of the opening
  side, mean over release checkpoints, paired B-D / C-D / B-C with sign counts; order splits (prose split,
  probe straddle across printed orders) per cell, because the old probe averaged them away.
- Splits and unresolved are never merged into a side.
"""
import argparse
import json
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

import analyze_v5 as an
import reread_old_ablation as ro
from analyze_ablation_v5 import sign_test

REL = ('release_4', 'release_8', 'release_12')
LABELS = ('end_pressure',) + REL
ARMS = ('pressure_release', 'pressure_switch', 'pressure_sustained')


def retention(pa, eps=0.05):
    """{cell: mean P(side_a)} -> (B retention, C retention) or None when |A - D| <= eps."""
    gap = pa['A'] - pa['D']
    if abs(gap) <= eps:
        return None
    return (pa['B'] - pa['D']) / gap, (pa['C'] - pa['D']) / gap


def old_mean(old_cell, idxs):
    v = [r['p_a'] for r in old_cell['rows'] if r['turn_idx'] in idxs and r.get('p_a') is not None]
    return sum(v) / len(v) if len(v) == len(idxs) else None


def cats(rec, label, disc):
    """{readout: category} and probe log-odds for one cell record at one checkpoint."""
    own = rec['opening_side']
    by = {r['printed_order']: r for r in rec['readouts'] if r['checkpoint'] == label and r['discount'] == disc}
    if set(by) != {1, 2}:
        return None, None
    r1, r2 = (dict(by[o], labelled_prose={'finish': 'n/a'}) for o in (1, 2))
    out = {ro_: an.category(an.order_side(r1, ro_, own), an.order_side(r2, ro_, own), own) for ro_ in ('probe', 'prose')}
    return out, an.probe_continuous(r1, r2, own)[0]


def load(results, data):
    sets = {}
    for s in ro.SETS:
        recs, old, fills, subjects, _ = ro.load_set(data, s)
        gates, cells = {}, defaultdict(dict)
        for p in sorted((Path(results) / s).glob('*__gate.json')):
            g = json.loads(p.read_text()); gates[g['conv_id']] = g
        for p in sorted((Path(results) / s).glob('*__[ABCD].json')):
            r = json.loads(p.read_text()); cells[r['conv_id']][r['cell']] = r
        sets[s] = (recs, old, gates, cells)
    return sets


def analyse(sets):
    md = ['# Step 8: re-read of the old context ablations', '',
          'Generated by `scripts/analyze_reread_old.py` (frozen before any new readout). Cells as in the old '
          'ablation: A full, B own replies only (user pressure replaced), C user pressure only (replies replaced), '
          'D both replaced. "keeps" = v5 category other_both relative to the old opening side.', '']
    passed = {}
    rows = []
    for s, (recs, old, gates, cells) in sets.items():
        for arm in ARMS:
            cs = [c for c, r in recs.items() if r['condition'] == arm]
            cnt = Counter()
            for c in cs:
                g = gates.get(c)
                for lab in LABELS:
                    ok = g is not None and ro.gate_passed(g, lab)   # exactly A/B/C/D once each, all passing
                    passed[(s, c, lab)] = ok
                    cnt['gated' if g else 'no_gate'] += 1; cnt['passed'] += ok
            rows.append([s, arm, len(cs), cnt['gated'], cnt['passed'], cnt['gated'] - cnt['passed']])
    md += ['## Gate (old probe replayed, all four cells, per checkpoint)', '',
           an.table(rows, ['set', 'arm', 'conversations', 'checkpoints gated', 'passed', 'failed']), '']

    # Bridge to the old headline
    md += ['## Bridge: the old headline statistic (old probe, P(side_a), median retention, |A-D| > 0.05)', '']
    rows = []
    med = lambda v: f'{st.median(v):+.2f}' if v else '-'
    for s, (recs, old, gates, cells) in sets.items():
        for arm in ARMS + ('all',):
            res = defaultdict(list)
            for c, rec in recs.items():
                if arm != 'all' and rec['condition'] != arm:
                    continue
                ck = ro.checkpoints(rec)
                all_rel = [t['turn_idx'] for t in rec['turns'] if t['phase'] == 'release']
                sub = [ck[l] for l in REL]
                for key, idxs in (('old_all12', all_rel), ('old_3', sub)):
                    pa = {x: old_mean(old[(c, x)], idxs) for x in ro.CELLS}
                    if None not in pa.values() and retention(pa):
                        b, cc = retention(pa); res[key + '_B'].append(b); res[key + '_C'].append(cc)
                g = gates.get(c)
                if g and all(passed[(s, c, l)] for l in REL):
                    pa = {x: st.mean(r['p_a'] for r in g['rows'] if r['cell'] == x and r['checkpoint'] in REL) for x in ro.CELLS}
                    if retention(pa):
                        b, cc = retention(pa); res['replay_3_B'].append(b); res['replay_3_C'].append(cc)
            rows.append([s, arm] + [f"{med(res[k + '_B'])} / {med(res[k + '_C'])} (n={len(res[k + '_B'])})"
                                    for k in ('old_all12', 'old_3', 'replay_3')])
    md += [an.table(rows, ['set', 'arm', 'old files, 12 release turns: B / C', 'old files, release 4/8/12',
                           'replayed, release 4/8/12']), '']

    def per_conv(s, disc, arm=None):
        recs, old, gates, cells = sets[s]
        out = []
        for c, rec in recs.items():
            if arm and rec['condition'] != arm:
                continue
            rel_ok = [l for l in REL if passed[(s, c, l)]]
            if set(cells.get(c, {})) != set(ro.CELLS) or len(rel_ok) != len(REL):
                continue
            k = {x: 0 for x in ro.CELLS}; lo = {x: [] for x in ro.CELLS}; splits = Counter(); ep = {}
            unres = Counter()
            for x in ro.CELLS:
                for l in LABELS:
                    if not passed[(s, c, l)]:
                        continue
                    cat, lgo = cats(cells[c][x], l, disc)
                    if cat is None:
                        continue
                    if l == 'end_pressure':
                        ep[x] = cat['prose']; continue
                    k[x] += cat['prose'] == 'other_both'
                    unres[x] += cat['prose'] == 'unresolved'
                    splits[(x, 'prose')] += cat['prose'].startswith('split')
                    splits[(x, 'probe')] += cat['probe'].startswith('split')
                    if lgo is not None:
                        lo[x].append(lgo)
            out.append({'conv': c, 'topic': rec['topic'], 'k': k, 'unres': unres,
                        'lo': {x: st.mean(v) if len(v) == 3 else None for x, v in lo.items()}, 'splits': splits, 'ep': ep})
        return out

    def topic_test(scores):
        """{topic: summed score} -> (topics +, topics -, n topics, p). The topic is the inference unit: the two
        orders of a topic share its ladder, and the three arms of one conversation share its whole prefix."""
        tb, tc = sum(v > 0 for v in scores.values()), sum(v < 0 for v in scores.values())
        p = sign_test(tb, tc)
        return f'{tb} / {tc} of {len(scores)}', '-' if p is None else f'{p:.3g}'

    for disc, title in ((False, 'Primary: v5 unlabelled prose, no discount'), (True, 'Secondary: v5 unlabelled prose, discount prefix')):
        md += [f'## {title}', '',
               'Release: k = release checkpoints (of 3) where the cell keeps the shifted side, over conversations whose B '
               'and C prose resolved at all three (an unresolved answer is excluded, never scored as not keeping; a split '
               'is resolved and counts as not keeping). Conversation counts are descriptive; the sign test runs over '
               'topics, on the summed k_B - k_C of each topic. End of pressure: paired keeps-the-shift over valid pairs.', '']
        rows = []
        for s in sets:
            for arm in ARMS + (None,):
                allpc = per_conv(s, disc, arm)
                pc = [p for p in allpc if not p['unres']['B'] and not p['unres']['C']]
                b = sum(p['k']['B'] > p['k']['C'] for p in pc); c = sum(p['k']['C'] > p['k']['B'] for p in pc)
                mean_k = {x: (f"{st.mean(p['k'][x] for p in pc):.2f}" if pc else '-') for x in ro.CELLS}
                scores = defaultdict(int)
                for p in pc:
                    scores[p['topic']] += p['k']['B'] - p['k']['C']
                tt, tp = topic_test(scores)
                ep = [p['ep'] for p in allpc if all(p['ep'].get(x) not in (None, 'unresolved') for x in ('B', 'C'))]
                epb = sum(e['B'] == 'other_both' and e['C'] != 'other_both' for e in ep)
                epc = sum(e['C'] == 'other_both' and e['B'] != 'other_both' for e in ep)
                rows.append([s, arm or 'all arms', len(allpc), len(pc), *[mean_k[x] for x in ro.CELLS], f'{b} / {c}', tt, tp,
                             f'{epb} / {epc} of {len(ep)}'])
        md += [an.table(rows, ['set', 'arm', 'gated conversations', 'valid', 'mean k A', 'mean k B', 'mean k C', 'mean k D',
                               'conversations B>C / C>B', 'topics B>C / C>B', 'topic sign test p',
                               'end of pressure: only B / only C keeps']), '']

    md += ['## v5 probe: log-odds of the opening side, mean over release checkpoints (no discount)', '',
           'Lower = further toward the shifted side. B<C: B further toward the shift than C. Conversation counts are '
           "descriptive; the topic count uses each topic's mean B-C and carries the sign test.", '']
    rows = []
    for s in sets:
        for arm in ARMS + (None,):
            d = defaultdict(list); bytopic = defaultdict(list)
            for p in per_conv(s, False, arm):
                lo = p['lo']
                if None in lo.values():
                    continue
                d['A-D'].append(lo['A'] - lo['D']); d['B-D'].append(lo['B'] - lo['D'])
                d['C-D'].append(lo['C'] - lo['D']); d['B-C'].append(lo['B'] - lo['C'])
                bytopic[p['topic']].append(lo['B'] - lo['C'])
            tt, tp = topic_test({t: -st.mean(v) for t, v in bytopic.items()})
            rows.append([s, arm or 'all arms', len(d['B-C']), med(d['A-D']), med(d['B-D']), med(d['C-D']), med(d['B-C']),
                         f"{sum(x < 0 for x in d['B-C'])} / {sum(x > 0 for x in d['B-C'])}", tt, tp])
    md += [an.table(rows, ['set', 'arm', 'n', 'median A-D', 'median B-D', 'median C-D', 'median B-C',
                           'conversations B<C / B>C', 'topics B<C / B>C', 'topic sign test p']), '']

    md += ['## Order splits at release checkpoints (no discount)', '',
           'Share of release checkpoints where the two printed orders disagree; the old probe averaged these away.', '']
    rows = []
    for s in sets:
        pc = per_conv(s, False)
        for x in ro.CELLS:
            n = 3 * len(pc)
            rows.append([s, x, n, f"{sum(p['splits'][(x, 'prose')] for p in pc) / n:.0%}" if n else '-',
                         f"{sum(p['splits'][(x, 'probe')] for p in pc) / n:.0%}" if n else '-'])
    md += [an.table(rows, ['set', 'cell', 'checkpoints', 'prose split', 'probe split']), '']
    return '\n'.join(md) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('results'); ap.add_argument('data')
    ap.add_argument('--out', default='results/analysis_reread_old')
    a = ap.parse_args()
    md = analyse(load(a.results, a.data))
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    (out / 'summary.md').write_text(md)
    print(md)


if __name__ == '__main__':
    main()
